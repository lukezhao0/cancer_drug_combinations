"""Score the M5 zero-shot memory probe against the hidden outcomes (evaluation code; reads labels).

For each probe run (`runs/m5_probe/<model>[-masked]/predictions.parquet`) and each outcome:
Spearman correlation of the LLM's scores with the measured value, overall and per fame group (M2),
with a bootstrap 95% CI, and the hit rate among the LLM's top 10% against the sample's base rate.

A correlation near 0 on famous pairs means the model does not recall these screen results; a
clearly positive one, larger on famous than obscure pairs, is the memory the M6 agent could exploit
without reasoning, and the famous/obscure split of every M6 metric has to be read against it.

    uv run python -m combo_agent.eval.memory_probe runs/m5_probe/* --out artifacts/m5/memory_probe.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from combo_agent.data import paths
from combo_agent.lab.splits import FAME_ORDER, KEY

TARGETS = {"syn": ("y_syn", "is_hit_syn", "synergy (Bliss)"), "inh": ("y_inh", "is_hit_inh", "killing (CSS)")}
TOP_FRAC = 0.10
N_BOOT = 2000


def _rho(x: np.ndarray, y: np.ndarray) -> float:
    if len(x) < 3 or np.all(x == x[0]) or np.all(y == y[0]):
        return float("nan")
    return float(spearmanr(x, y).statistic)


def spearman_ci(x: np.ndarray, y: np.ndarray, n: int = N_BOOT, seed: int = 0) -> tuple[float, float, float]:
    """Spearman rho and a paired-bootstrap 95% CI."""
    rho = _rho(x, y)
    rng = np.random.default_rng(seed)
    boots = [_rho(x[i], y[i]) for i in (rng.integers(0, len(x), len(x)) for _ in range(n))]
    boots = np.array([b for b in boots if not np.isnan(b)])
    if len(boots) < n // 2:
        return rho, float("nan"), float("nan")
    return rho, float(np.quantile(boots, 0.025)), float(np.quantile(boots, 0.975))


def top_hit_rate(pred: np.ndarray, hit: np.ndarray, frac: float = TOP_FRAC) -> float:
    k = max(1, int(round(len(pred) * frac)))
    # stable order so ties are broken by sample order, not by the label
    order = np.argsort(-pred, kind="stable")[:k]
    return float(hit[order].mean())


def load_labels(processed: Path | None = None) -> pd.DataFrame:
    processed = processed or paths.processed_dir()
    return pd.read_parquet(processed / "labels.parquet", columns=[*KEY, "y_syn", "y_inh", "is_hit_syn", "is_hit_inh"])


def score(preds: pd.DataFrame, labels: pd.DataFrame) -> pd.DataFrame:
    df = preds.merge(labels, on=KEY, how="left", validate="one_to_one")
    if df.y_syn.isna().any():
        raise ValueError("probe predictions name experiments that are not in the pool")
    rows = []
    for t, (ycol, hcol, _) in TARGETS.items():
        pcol = f"pred_{t}"
        for group in ("all", *FAME_ORDER):
            g = df if group == "all" else df[df.fame == group]
            g = g[g[pcol].notna()]
            rho, lo, hi = spearman_ci(g[pcol].to_numpy(float), g[ycol].to_numpy(float))
            rows.append({"target": t, "group": group, "n": len(g), "rho": rho, "ci_lo": lo, "ci_hi": hi,
                         "top10_hit_rate": top_hit_rate(g[pcol].to_numpy(float), g[hcol].to_numpy(bool)) if len(g) else np.nan,
                         "base_hit_rate": float(g[hcol].mean()) if len(g) else np.nan})
    return pd.DataFrame(rows)


def _fmt(x: float, nd: int = 2) -> str:
    return "–" if pd.isna(x) else f"{x:.{nd}f}"


def report(results: dict[str, tuple[pd.DataFrame, dict, pd.DataFrame]]) -> str:
    out = ["# M5 zero-shot memory probe", "",
           "Generated by `combo_agent.eval.memory_probe`. The LLM scored 200 selectable pool experiments "
           "(stratified by pair fame, seed 0) for expected synergy and killing, with no tools. ρ is the "
           "Spearman correlation with the measured outcome (95% bootstrap CI). \"Top-10% hits\" is the hit "
           "rate among the 10% of experiments the LLM scored highest, against the group's base rate.", ""]
    runs = []
    for name, (tab, man, preds) in results.items():
        cost = man.get("cost_usd_uncached")
        runs.append(f"| {name} | {man.get('model')} | {'yes' if man.get('masked') else 'no'} | "
                    f"{man.get('answered')}/{man.get('n')} | {_fmt(cost, 4) if cost is not None else '?'} | "
                    f"{_fmt(_rho(preds.pred_syn.to_numpy(float), preds.pred_inh.to_numpy(float)))} |")
    out += ["| Run | Model | Masked | Answered | Cost (USD, uncached) | ρ(pred syn, pred kill) |",
            "|:--|:--|:--|--:|--:|--:|", *runs, ""]
    for t, (_, _, label) in TARGETS.items():
        out += [f"## Target `{t}`: {label}", "",
                "| Run | Group | n | ρ (95% CI) | Top-10% hits | Base rate |", "|:--|:--|--:|:--|--:|--:|"]
        for name, (tab, _, _) in results.items():
            for r in tab[tab.target == t].itertuples():
                out.append(f"| {name} | {r.group} | {r.n} | {_fmt(r.rho)} ({_fmt(r.ci_lo)} to {_fmt(r.ci_hi)}) | "
                           f"{_fmt(r.top10_hit_rate)} | {_fmt(r.base_hit_rate)} |")
        out.append("")
    return "\n".join(out)


def build(run_dirs: list[Path], out: Path | None = None, processed: Path | None = None) -> str:
    labels = load_labels(processed)
    results = {}
    for d in sorted(run_dirs):
        preds = pd.read_parquet(d / "predictions.parquet")
        man = json.loads((d / "manifest.json").read_text())
        tab = score(preds, labels)
        tab.to_csv(d / "scores.csv", index=False)
        results[d.name] = (tab, man, preds)
    text = report(results)
    for d in run_dirs:
        (d / "report.md").write_text(report({d.name: results[d.name]}))
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m combo_agent.eval.memory_probe")
    ap.add_argument("runs", nargs="+", type=Path)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args(argv)
    print(build([d for d in args.runs if (d / "predictions.parquet").exists()], args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
